import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { collectTranslationPaths, getByPath, type Tree } from '@i18n-micro/core'
import { loadTranslationDir } from '@i18n-micro/utils/load-dir'

export interface GeneratorOptions {
  srcDir: string
  /** One folder or several (layers, additional dirs); each is resolved against `srcDir`. */
  translationDir: string | string[]
  outputFile?: string // Where to put the d.ts file
}

/**
 * Emit a TS property name from a translation key.
 * JSON.stringify covers quotes/newlines/null bytes; U+2028/U+2029 need an extra escape
 * so the .d.ts stays safe when embedded in older JS tooling.
 */
export function formatKeyProperty(key: string): string {
  return JSON.stringify(key)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
}

function typeOf(value: unknown): string {
  if (value === null) return 'null'
  if (Array.isArray(value)) return 'unknown[]'
  return typeof value
}

/** Every key `t()` can answer in `dictionary`, objects too, with the type of its value. */
function addKeys(keys: Map<string, Set<string>>, dictionary: Tree): void {
  const paths = new Set<string>()
  collectTranslationPaths(dictionary, paths)
  for (const path of paths) {
    const types = keys.get(path) ?? new Set()
    keys.set(path, types.add(typeOf(getByPath(dictionary, path))))
  }
}

/**
 * Generates a string with TypeScript types for translation keys.
 * Does not write a file, only returns content.
 *
 * @param options - Generator options
 * @returns String with .d.ts file content
 */
export function getTypesString(options: GeneratorOptions): string {
  const keys = new Map<string, Set<string>>()
  for (const dir of [options.translationDir].flat()) {
    const { root, routes } = loadTranslationDir(resolve(options.srcDir, dir))
    for (const dictionary of [root, ...Object.values(routes)].flatMap((bucket) => Object.values(bucket))) addKeys(keys, dictionary)
  }

  const keysContent = [...keys]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([key, types]) => `    ${formatKeyProperty(key)}: ${[...types].sort().join(' | ')};`)
    .join('\n')

  // Important: we extend the '@i18n-micro/types' module
  return `/* prettier-ignore */
// @ts-nocheck
// Generated by @i18n-micro/types-generator
// DO NOT EDIT THIS FILE MANUALLY

import '@i18n-micro/types';

declare module '@i18n-micro/types' {
  export interface DefineLocaleMessage {
${keysContent}
  }
}
`
}

/**
 * Generates TypeScript types for translation keys from JSON files.
 * Writes the result to a file.
 *
 * @param options - Generator options
 * @returns Path to the generated file
 */
export function generateTypes(options: GeneratorOptions): string {
  const outputPath = resolve(options.srcDir, options.outputFile || 'i18n-micro.d.ts')
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, getTypesString(options), 'utf-8')
  return outputPath
}
